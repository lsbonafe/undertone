"""Original drum one-shots and a C-major-nine electric-key chord, with no external recordings."""
import base64
import io
import math
from pathlib import Path
import random
import struct
import wave

rate = 22050
destination = Path(__file__).resolve().parents[1] / 'assets' / 'audio'
destination.mkdir(exist_ok=True)
rng = random.Random(418)

def encode(name, values):
    peak = max(abs(value) for value in values) or 1
    frames = b''.join(struct.pack('<h', round(value / peak * 0.8 * 32767)) for value in values)
    output = io.BytesIO()
    with wave.open(output, 'wb') as audio:
        audio.setnchannels(1)
        audio.setsampwidth(2)
        audio.setframerate(rate)
        audio.writeframes(frames)
    destination.joinpath(f'{name}.wav').write_bytes(output.getvalue())
    return 'data:audio/wav;base64,' + base64.b64encode(output.getvalue()).decode('ascii')

kick = []
phase = 0
for index in range(round(rate * 0.34)):
    time = index / rate
    phase += 2 * math.pi * (48 + 125 * math.exp(-time * 48)) / rate
    body = math.sin(phase) * math.exp(-time * 14)
    click = rng.uniform(-1, 1) * math.exp(-time * 220) * 0.12
    fade = min(1, time / 0.0015) * min(1, (0.34 - time) / 0.015)
    kick.append(math.tanh((body + click) * 2.4) * fade)

hat = []
previous = 0
for index in range(round(rate * 0.065)):
    time = index / rate
    noise = rng.uniform(-1, 1)
    high = noise - previous
    previous = noise
    hat.append(high * math.exp(-time * 75) * min(1, time / 0.001) * min(1, (0.065-time)/0.008))

snare = []
previous = 0
for index in range(round(rate * 0.18)):
    time = index / rate
    noise = rng.uniform(-1, 1)
    high = noise - previous * 0.65
    previous = noise
    body = math.sin(2*math.pi*180*time) * math.exp(-time*28)
    snare.append((high*math.exp(-time*24)*0.7 + body*0.3) * min(1,time/0.001) * min(1,(0.18-time)/0.015))

tape = []
for index in range(round(rate * 1.4)):
    time = index / rate
    value = 0
    for semitones in [0, 4, 7, 11, 14]:
        hz = 261.625565 * 2 ** (semitones / 12)
        phase = 2 * math.pi * hz * time + 0.035 * math.sin(2*math.pi*0.38*time)
        value += (math.sin(phase) + 0.2*math.sin(2*phase) + 0.08*math.sin(3*phase)) / 5
    envelope = min(1,time/0.018) * math.exp(-time*1.8) * min(1,(1.4-time)/0.08)
    tape.append(value * envelope)

encoded = {
    'u_kick': encode('genre-kick', kick),
    'u_hat': encode('genre-hat', hat),
    'u_snare': encode('genre-snare', snare),
    'u_tape': encode('genre-tape', tape),
}
destination.joinpath('genre-samples.js').write_text(
    '// Original recordings generated by scripts/make-genre-samples.py.\n'
    'export const genreSamples = ' + repr(encoded) + ';\n')
