"""Create an original pitched strike; the embedded WAV needs no sample service."""
import base64
import io
import math
from pathlib import Path
import struct
import wave

rate = 22050
duration = 0.8
frequency = 261.625565
partials = [1, 0.28, 0.12, 0.06]
frames = bytearray()
for index in range(round(rate * duration)):
    time = index / rate
    attack = min(1, time / 0.006)
    envelope = attack * math.exp(-4.5 * time)
    tail = min(1, (duration - time) / 0.04)
    value = sum(amplitude * math.sin(2 * math.pi * frequency * harmonic * time)
                for harmonic, amplitude in enumerate(partials, 1))
    frames.extend(struct.pack('<h', round(value * envelope * tail * 0.55 * 32767)))
output = io.BytesIO()
with wave.open(output, 'wb') as audio:
    audio.setnchannels(1)
    audio.setsampwidth(2)
    audio.setframerate(rate)
    audio.writeframes(frames)
destination = Path(__file__).resolve().parents[1] / 'assets' / 'audio'
destination.mkdir(exist_ok=True)
destination.joinpath('porcelain.wav').write_bytes(output.getvalue())
encoded = base64.b64encode(output.getvalue()).decode('ascii')
destination.joinpath('porcelain.js').write_text(
    '// Original C4 strike, generated by scripts/make-porcelain.py.\n'
    f"export const porcelainSample = 'data:audio/wav;base64,{encoded}';\n")
