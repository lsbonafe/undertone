import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { setTimeout as delay } from 'node:timers/promises';
import * as webaudio from 'node-web-audio-api';
import { IDLE_MS, midiOf } from '../motion.js';
import { stories } from '../stories.js';
import { SoundControl } from '../sound-control.js';

// One audio context per process mirrors the browser and keeps Strudel's node pool on its own context.
Object.assign(globalThis, webaudio);
globalThis.window = new EventTarget();
globalThis.document = new EventTarget();
const strudel = await import('../assets/vendor/strudel.mjs');
const { compileScore, ScrollInstrument } = await import('../music.js');
const scores = new Map();
for (const id of Object.keys(stories)) scores.set(id, await compileScore(await readFile(new URL(`../scores/${id}.strudel`, import.meta.url), 'utf8')));

test('pausing holds audible harmony without advancing the melody; resume, mute, and story changes remain responsive', async t => {
  // A silent native sink exercises real-time AudioParams without playing through the Mac speakers.
  const context = new webaudio.AudioContext({ sinkId: { type: 'none' } });
  strudel.setAudioContext(context);
  strudel.setSuperdoughAudioController(undefined);
  let direction;
  let phase;
  let attacks = 0;
  const errors = [];
  const instrument = new ScrollInstrument((notes, value) => { assert.ok(notes.every(note => midiOf(note) !== null), 'pitch display receives only pitched notes'); direction = value; attacks++; }, value => { phase = value; }, error => errors.push(error));
  t.after(async () => { instrument.mute(); await context.close(); });
  await instrument.enable();
  instrument.setScore(scores.get('space').events);
  const analyser = context.createAnalyser();
  instrument.controller.output.destinationGain.connect(analyser);
  // Native AudioParam changes become observable after the next render quantum.
  await delay(80);
  assert.ok(instrument.gain.value > 0);
  assert.equal(instrument.holding, true);
  instrument.move(0.025);
  await delay(45);
  assert.ok(instrument.gain.value > 0);
  assert.equal(direction, 'forward');
  await delay(IDLE_MS + 65);
  assert.ok(instrument.gain.value > 0, 'a pause keeps the harmony sounding');
  assert.equal(phase, 'hold');
  assert.equal(instrument.harmony.holding, true);
  assert.equal(instrument.harmony.renderProfile.comfort, true);
  assert.equal(attacks, 1, 'a pause does not keep the song running in the background');
  const held = [...instrument.harmony.notes];
  await delay(2300);
  assert.equal(attacks, 1);
  assert.deepEqual(instrument.harmony.notes, held, 'a held moment does not change harmony');
  const samples = new Float32Array(analyser.fftSize);
  analyser.getFloatTimeDomainData(samples);
  const rms = Math.sqrt(samples.reduce((sum, value) => sum + value * value, 0) / samples.length);
  assert.ok(rms > 0.0001, `the held harmony remains audible after the former cutoff: RMS ${rms}`);
  const sameHarmony = instrument.harmony;
  instrument.move(0.045);
  assert.equal(attacks, 2, 'resuming immediately continues the phrasing');
  assert.equal(instrument.harmony, sameHarmony, 'resuming preserves the continuous sound layer');
  assert.equal(instrument.harmony.holding, false);
  await delay(40);
  assert.ok(instrument.gain.value > 0);
  await delay(280);
  assert.ok(instrument.gain.value > 0);
  assert.equal(attacks, 2);
  instrument.move(0.005);
  assert.equal(direction, 'backward');
  instrument.mute();
  await delay(20);
  assert.ok(instrument.gain.value >= 0 && instrument.gain.value <= 0.55, 'interrupting the attack cannot invert or amplify output');
  await delay(60);
  assert.equal(instrument.gain.value, 0);
  assert.equal(instrument.enabled, false);
  assert.equal(instrument.harmony, null);
  instrument.setScore(scores.get('reef').events, 0.5);
  await delay(20);
  assert.equal(instrument.gain.value, 0);
  assert.equal(instrument.lastProgress, 0.5);
  assert.equal(instrument.events, scores.get('reef').events);
  await instrument.enable();
  assert.equal(instrument.holding, true);
  const previousHarmony = instrument.harmony;
  instrument.setScore(scores.get('space').events);
  assert.equal(previousHarmony.disposed, true, 'changing stories releases the previous harmony');
  assert.notEqual(instrument.harmony, previousHarmony);
  assert.equal(instrument.holding, true);
  for (const [id, kind] of [['erosion','subtractive'], ['fireflies','additive'], ['bell','fm'], ['loss','pure'], ['minab','additive'], ['election','fm'], ['routes','additive'], ['worldcup','subtractive'], ['displacement','fm'], ['laundromat','subtractive'], ['chess','subtractive'], ['bakery','subtractive'], ['porcelain','additive'], ['library','subtractive']]) {
    instrument.setScore(scores.get(id).events);
    assert.equal(instrument.harmony.profile.kind, kind);
    instrument.move(0.02);
    await delay(IDLE_MS + 30);
    assert.equal(instrument.holding, true);
    assert.equal(instrument.harmony.profile.kind, kind, `${id}: a pause keeps the sound-making method`);
  }
  for (const id of ['mall', 'vhs', 'courier']) {
    instrument.setScore(scores.get(id).events, 0, stories[id].playback);
    instrument.controller.output.destinationGain.connect(analyser);
    const groove = instrument.groove;
    assert.equal(instrument.harmony, null, `${id}: a groove hold never creates a replacement drone`);
    assert.equal(instrument.holding, true);
    const before = { bar:groove.bar, step:groove.groupIndex };
    await delay(2050);
    assert.ok(groove.bar > before.bar || groove.groupIndex > before.step, `${id}: the groove clock continues through percussion without scroll input`);
    assert.equal(groove.lastGestureAt, -Infinity, `${id}: the foreground waits for the reader's hand`);
    analyser.getFloatTimeDomainData(samples);
    assert.ok(samples.some(value => Math.abs(value) > 0.0001), `${id}: the held groove is audible`);
    const previousGesture = groove.lastGestureAt;
    const movedAt = context.currentTime;
    instrument.move(24 / (900 * 4), performance.now(), 4);
    await delay(150);
    assert.ok(groove.lastGestureAt > previousGesture && groove.lastGestureAt - movedAt <= 0.15, `${id}: a small scroll reaches the foreground player promptly`);
    instrument.move(0.96);
    const brightTarget = instrument.grooveTone.target;
    assert.ok(brightTarget > (stories[id].playback.character === 'vaporwave' ? 2000 : 6000), 'a flick immediately shapes already-ringing notes');
    instrument.move(0.01);
    assert.equal(instrument.groove, groove, 'scrolling never restarts the musical clock');
    assert.equal(groove.direction, 'backward');
    await delay(IDLE_MS + 60);
    assert.equal(instrument.holding, true);
    assert.equal(instrument.harmony, null);
    assert.equal(phase, 'loop');
    instrument.mute();
    const mutedAttacks = attacks;
    await delay(100);
    assert.equal(attacks, mutedAttacks, 'mute cancels the repeating scheduler');
    assert.equal(instrument.gain.value, 0);
    assert.equal(instrument.pulse, null);
    assert.equal(instrument.groove, null);
    await instrument.enable();
    assert.ok(instrument.groove, 'enabling again starts a fresh groove');
    instrument.silence();
    assert.equal(instrument.pulse, null, 'hiding the page stops the clock');
    document.hidden = true;
    instrument.setScore(scores.get(id).events, 0.7, stories[id].playback);
    assert.equal(instrument.groove, null, 'a delayed score load cannot restart a hidden page');
    document.hidden = false;
    instrument.setPosition(0.7);
    instrument.holdCurrent();
    assert.equal(instrument.groove.wantedPassage, 2, 'returning to the page starts at its current passage');
  }
  instrument.setScore(scores.get('space').events);
  assert.equal(instrument.groove, null, 'switching to an earlier story stops groove playback');
  assert.ok(instrument.harmony, 'the original held-note strategy still works after leaving a groove');
  const resume = context.resume.bind(context);
  let unlock;
  context.resume = () => new Promise(resolve => { unlock = resolve; });
  const waiting = instrument.enable();
  instrument.mute();
  unlock();
  assert.equal(await waiting, false, 'a pause cancels an autoplay attempt waiting on permission');
  assert.equal(instrument.enabled, false);
  assert.equal(instrument.harmony, null, 'a late resume cannot briefly start the held sound');
  assert.equal(instrument.pulse, null);
  context.resume = resume;
  await context.suspend();
  let permitResume = false;
  const permission = new Promise(resolve => { unlock = resolve; });
  context.resume = () => {
    if (permitResume) resume().then(unlock);
    return permission;
  };
  const sound = new SoundControl(instrument, { storage:{ getItem:() => null, setItem:() => {} } });
  const awaitingPermission = sound.start();
  assert.deepEqual(sound.control, { label:'Enable sound', pressed:false }, 'a real suspended context cannot present an active sound control');
  permitResume = true;
  await sound.toggle();
  assert.equal(await awaitingPermission, true);
  assert.equal(context.state, 'running');
  assert.deepEqual(sound.control, { label:'Pause sound', pressed:true }, 'the first Enable action starts the actual audio instrument');
  assert.ok(instrument.harmony);
  sound.pause();
  await delay(60);
  assert.equal(instrument.gain.value, 0);
  context.resume = resume;
  assert.deepEqual(errors, []);
});
